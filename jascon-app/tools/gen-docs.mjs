/* Writes the generated parts of jascon-app/readme.md from the code.

     node jascon-app/tools/gen-docs.mjs          rewrite readme.md
     node jascon-app/tools/gen-docs.mjs --check  exit 1 if readme.md is stale

   Generated today: the settings table, from JSC_CFG in jascon-core.js. The
   text between the two marker comments in readme.md is replaced; everything
   else in the file is written by hand. Running it twice changes nothing.
   tests/docs.test.mjs fails when the table and the code disagree. */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const README = path.join(APP, "readme.md");
const START = "<!-- settings:start (generated by tools/gen-docs.mjs, do not edit) -->";
const END = "<!-- settings:end -->";

export function settingsTable() {
  const { JSC_CFG } = createRequire(import.meta.url)("../jascon-core.js");
  const cell = s => String(s).replace(/\|/g, "\\|");
  const rows = JSC_CFG.map(c => {
    const values = c.choices ? c.choices.map(v => (v === "" ? "(empty)" : "`" + v + "`")).join(", ") : "text";
    const def = c.def === "" ? "(empty)" : "`" + c.def + "`";
    return `| \`${c.key}\` | ${cell(c.label)} | ${values} | ${def} | ${cell(c.help)} |`;
  });
  return ["| Key | Setting | Values | Default | Note |", "|---|---|---|---|---|", ...rows].join("\n");
}
export function render(readme) {
  const a = readme.indexOf(START), b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error("readme.md has no settings markers");
  return readme.slice(0, a + START.length) + "\n" + settingsTable() + "\n" + readme.slice(b);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const now = fs.readFileSync(README, "utf8"), want = render(now);
  if (process.argv.includes("--check")) {
    if (now !== want) { console.error("readme.md is stale; run node jascon-app/tools/gen-docs.mjs"); process.exit(1); }
    console.log("readme.md is up to date");
  } else if (now !== want) { fs.writeFileSync(README, want); console.log("readme.md rewritten"); }
  else console.log("readme.md unchanged");
}
