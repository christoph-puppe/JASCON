/* Writes jascon-app/jascon-presets.js: the scales and risk catalogues the
   repository ships, as one script the risk page can load without fetching.

     node jascon-app/tools/gen-presets.mjs          rewrite jascon-presets.js
     node jascon-app/tools/gen-presets.mjs --check  exit 1 if it is stale

   Sources, read as they are and never edited here:
     risk-catalogs/scales/*.json            three starting scales, one with a 3x3 matrix
     jascon/examples/scale-*.json           three scales in the style of BSI 200-3, one with a 4x4 matrix
     risk-catalogs/<name>/catalog.json and entries/*.json   the risk catalogues
   tests/tools.test.mjs fails when the generated file and the sources
   disagree. Running it twice changes nothing. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = path.resolve(APP, "..");
const OUT = path.join(APP, "jascon-presets.js");
const read = f => JSON.parse(fs.readFileSync(path.join(ROOT, f), "utf8"));
const jsonIn = dir => fs.readdirSync(path.join(ROOT, dir)).filter(f => f.endsWith(".json")).sort();

export function render() {
  const scaleSets = [
    { key: "three-levels", source: "risk-catalogs/scales", scales: jsonIn("risk-catalogs/scales").map(f => read("risk-catalogs/scales/" + f)) },
    { key: "bsi-200-3-style", source: "jascon/examples", scales: jsonIn("jascon/examples").filter(f => f.startsWith("scale-")).map(f => read("jascon/examples/" + f)) },
  ];
  const catalogs = ["office-it", "industrial-plant"].map(name => {
    const catalog = read(`risk-catalogs/${name}/catalog.json`);
    const byId = new Map(jsonIn(`risk-catalogs/${name}/entries`).map(f => read(`risk-catalogs/${name}/entries/${f}`)).map(e => [e.id, e]));
    const members = [...catalog.members].sort((a, b) => a.sequence - b.sequence).map(m => m.ref);
    const missing = members.filter(m => !byId.has(m)), extra = [...byId.keys()].filter(id => !members.includes(id));
    if (missing.length || extra.length) throw new Error(`${name}: catalogue and entries disagree (${missing.length} members without a file, ${extra.length} files that are no member)`);
    return { catalog, entries: members.map(m => byId.get(m)) };
  });
  return `/* GENERATED by tools/gen-presets.mjs from risk-catalogs/ and jascon/examples/ - do not edit.
   JSC_PRESETS.scaleSets: groups of scale definitions that belong together (a
   level scale with its matrix and the two scales the matrix combines).
   JSC_PRESETS.catalogs: risk catalogues, each with its entries in catalogue order. */
"use strict";
const JSC_PRESETS = ${JSON.stringify({ scaleSets, catalogs })};
if (typeof module !== "undefined" && module.exports) module.exports = { JSC_PRESETS };
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const want = render(), now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (process.argv.includes("--check")) {
    if (now !== want) { console.error("jascon-presets.js is stale; run node jascon-app/tools/gen-presets.mjs"); process.exit(1); }
    console.log("jascon-presets.js is up to date");
  } else if (now !== want) { fs.writeFileSync(OUT, want); console.log("jascon-presets.js rewritten"); }
  else console.log("jascon-presets.js unchanged");
}
