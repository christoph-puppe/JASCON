/* Writes jascon-app/jascon-schema.js from the kernel schema and the stdlib
   facet descriptors under jascon/schemas/.

     node jascon-app/tools/gen-schema.mjs          rewrite jascon-schema.js
     node jascon-app/tools/gen-schema.mjs --check  exit 1 if it is stale

   The app cannot read jascon/schemas/ at run time: a page opened from
   file:// may not fetch, and the app folder may travel without the rest of
   the repository. So the schemas are carried as one script, generated here
   and never edited by hand. tests/tools.test.mjs fails when the generated
   file and the schemas disagree. Running it twice changes nothing. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMAS = path.resolve(APP, "../jascon/schemas");
const KERNEL = "oscal-semantic-core-2.0.0.schema.json";
const OUT = path.join(APP, "jascon-schema.js");

export function render() {
  const read = f => JSON.parse(fs.readFileSync(f, "utf8"));
  const kernel = read(path.join(SCHEMAS, KERNEL));
  const stdlib = fs.readdirSync(path.join(SCHEMAS, "stdlib")).filter(f => f.endsWith(".json")).sort()
    .map(f => read(path.join(SCHEMAS, "stdlib", f)));
  return `/* GENERATED by tools/gen-schema.mjs from jascon/schemas/ - do not edit.
   JSC_SCHEMA is the kernel schema (${KERNEL}); JSC_STDLIB are the
   standard-library facet descriptors, in file-name order. */
"use strict";
const JSC_SCHEMA = ${JSON.stringify(kernel)};
const JSC_STDLIB = ${JSON.stringify(stdlib)};
if (typeof module !== "undefined" && module.exports) module.exports = { JSC_SCHEMA, JSC_STDLIB };
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const want = render(), now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (process.argv.includes("--check")) {
    if (now !== want) { console.error("jascon-schema.js is stale; run node jascon-app/tools/gen-schema.mjs"); process.exit(1); }
    console.log("jascon-schema.js is up to date");
  } else if (now !== want) { fs.writeFileSync(OUT, want); console.log("jascon-schema.js rewritten"); }
  else console.log("jascon-schema.js unchanged");
}
