#!/usr/bin/env python3
"""Rewrites jascon-app/jascon-schema.js the way jascon-app/tools/gen-schema.mjs
does, for a machine without Node.

    uv run python drafts/cp-advice-1/regen_app_schema.py

gen-schema.mjs is the generator and tests/tools.test.mjs holds the file to
it. This script is a stand-in, and it proves it is a faithful one before it
writes: it renders the schemas of the last commit and requires the result
to equal the committed jascon-schema.js byte for byte. Only then does it
render the working tree. JSON.stringify and json.dumps(separators=(',',
':'), ensure_ascii=False) agree on these files; the proof is that check,
not this sentence."""
import json, os, subprocess, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
KERNEL = "jascon-2.0.0.schema.json"
OUT = os.path.join(ROOT, "jascon-app", "jascon-schema.js")

def render(read, names):
    js = lambda o: json.dumps(o, separators=(",", ":"), ensure_ascii=False)
    kernel = read("jascon/schemas/" + KERNEL)
    stdlib = [read("jascon/schemas/stdlib/" + n) for n in sorted(names)]
    return ("/* GENERATED by tools/gen-schema.mjs from jascon/schemas/ - do not edit.\n"
            f"   JSC_SCHEMA is the kernel schema ({KERNEL}); JSC_STDLIB are the\n"
            "   standard-library facet descriptors, in file-name order. */\n"
            '"use strict";\n'
            f"const JSC_SCHEMA = {js(kernel)};\n"
            f"const JSC_STDLIB = {js(stdlib)};\n"
            'if (typeof module !== "undefined" && module.exports) module.exports = { JSC_SCHEMA, JSC_STDLIB };\n')

def git(*a):
    return subprocess.run(["git", "-C", ROOT, *a], capture_output=True, check=True).stdout

head_names = [n for n in git("ls-tree", "--name-only", "HEAD", "jascon/schemas/stdlib/").decode().split()
              if n.endswith(".json")]
head = render(lambda p: json.loads(git("show", "HEAD:" + p).decode("utf-8")),
              [os.path.basename(n) for n in head_names])
committed = git("show", "HEAD:jascon-app/jascon-schema.js").decode("utf-8").replace("\r\n", "\n")
if head != committed:
    sys.exit("this stand-in does NOT reproduce the committed jascon-schema.js from the committed schemas; "
             "nothing written - run node jascon-app/tools/gen-schema.mjs instead")
print("stand-in reproduces the committed file from the committed schemas: byte-identical")

names = [n for n in os.listdir(os.path.join(ROOT, "jascon", "schemas", "stdlib")) if n.endswith(".json")]
want = render(lambda p: json.load(open(os.path.join(ROOT, *p.split("/")), encoding="utf-8")), names)
now = open(OUT, encoding="utf-8", newline="").read()
crlf = "\r\n" in now
if now.replace("\r\n", "\n") == want:
    print("jascon-schema.js unchanged")
else:
    open(OUT, "w", encoding="utf-8", newline="").write(want.replace("\n", "\r\n") if crlf else want)
    print("jascon-schema.js rewritten")
